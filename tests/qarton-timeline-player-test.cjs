'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const scene = require('../examples/qarton-single-load-scene.json');
const { createTimelinePlayer } = require('../scripts/qarton-timeline-player.js');
test('play/pause/tick/seek/replay use deterministic timeline', () => {
  const frames = [];
  const player = createTimelinePlayer(scene, frame => frames.push(frame));
  assert.equal(frames[0].positionMs, 0);
  assert.equal(frames[0].camera.shot, 'wide');
  assert.equal(frames[0].dialogue, null);
  player.play();
  player.tick(5500);
  assert.equal(frames.at(-1).dialogue.speaker, 'ryan');
  assert.equal(frames.at(-1).camera.shot, 'medium');
  player.pause();
  player.tick(3000);
  assert.equal(player.state.positionMs, 5500);
  player.seek(20500);
  assert.deepEqual(frames.at(-1).choices.choiceIds, ['prioritizeBridge','prioritizeClinic','splitWithLimits']);
  player.seek(999999);
  assert.equal(player.state.playing, false);
  assert.equal(player.state.positionMs, scene.durationMs);
  player.replay();
  assert.equal(player.state.positionMs, 0);
  assert.equal(player.state.playing, true);
  player.destroy();
  const count = frames.length;
  player.tick(1000);
  player.seek(1000);
  assert.equal(frames.length, count);
});
test('invalid timing and input fail closed', () => {
  assert.throws(() => createTimelinePlayer(null, () => {}), TypeError);
  assert.throws(() => createTimelinePlayer(scene, null), TypeError);
  const player = createTimelinePlayer(scene, () => {});
  assert.throws(() => player.seek(NaN), TypeError);
  player.play();
  assert.throws(() => player.tick(-1), TypeError);
  player.destroy();
});
