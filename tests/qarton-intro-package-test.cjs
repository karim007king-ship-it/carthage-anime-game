const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const source = fs.readFileSync(path.join(root, 'scripts/package-qarton-intro.cjs'), 'utf8');
assert.match(pkg.scripts['prepare:web'], /prepare-web\.cjs && node scripts\/package-qarton-intro\.cjs/);
assert.match(source, /QARTON_INTRO_ENABLE !== '1'/);
assert.match(source, /createHash\('sha256'\)/);
assert.match(source, /6b22dbc843affed208e066cb6c68044779683594e9826a52cb1f1619a53fe2ff/);
assert.match(source, /sessionStorage\.setItem\(key,'1'\)/);
assert.match(source, /prefers-reduced-motion/);
assert.match(source, /timeoutMs:10000/);
assert.match(source, /src:'\.\/qarton-intro\/official-intro\.mp4'/);
assert.doesNotMatch(source, /localStorage\.(setItem|removeItem|clear)/);
console.log('QARTON optional intro packaging contract verified.');
