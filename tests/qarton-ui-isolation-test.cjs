const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'..');
const runtime=fs.readFileSync(path.join(root,'scripts','qarton-isolated-home.js'),'utf8');
const prep=fs.readFileSync(path.join(root,'scripts','prepare-web.cjs'),'utf8');
const premium=fs.readFileSync(path.join(root,'scripts','qarton-premium-home.js'),'utf8');
const legacy=fs.readFileSync(path.join(root,'legacy','README.md'),'utf8');
assert.doesNotThrow(()=>new vm.Script(runtime));
for(const state of ['HOME','INTRO','GAME','TRANSITION'])assert.ok(runtime.includes(state),'missing lifecycle state '+state);
assert.ok(runtime.includes('window.__qartonSetAppState')&&runtime.includes('window.__qartonGetAppState'));
assert.ok(runtime.includes('window.dispatchEvent(new CustomEvent("qarton:statechange"'));
assert.ok(runtime.includes('function hideRoot()')&&runtime.includes('root.style.setProperty("display","none","important")'));
assert.ok(runtime.includes('function revealRoot(scene)')&&runtime.includes('scene==="INTRO"')&&runtime.includes('scene==="GAME"'));
assert.ok(runtime.includes('__carthageStartNewGame')&&runtime.includes('__carthageContinue'));
assert.ok(runtime.includes('__carthageSetDifficulty')&&runtime.includes('__carthageStartPart2')&&runtime.includes('__carthageStartPart3'));
assert.ok(!runtime.includes('findNativeMenu')&&!runtime.includes('home-actions')&&!runtime.includes('n.click()'),'QARTON must not discover or replay legacy home menu controls');
assert.ok(!runtime.includes('.game-timer')&&!runtime.includes('isPlaying'),'lifecycle must not infer state from incidental DOM');
assert.ok(runtime.includes('window.__QARTON_HOME_READY__=true'));
assert.ok(runtime.includes('function showConfirm()'),'new-game confirmation must be rendered in QARTON');
assert.ok(runtime.includes('window.__carthageHasFreeSlot')&&runtime.includes('حفظك السابق لن يُحذف'));
assert.ok(prep.includes('window.__carthageSetDifficulty=(index)=>'));
assert.ok(prep.includes('window.__carthageStartPart2=()=>'));
assert.ok(prep.includes('window.__carthageStartNewGame=()=>'));
assert.ok(prep.includes('window.__carthageContinue=()=>'));
assert.ok(prep.includes('window.__carthageStartPart3=()=>'));
assert.ok(prep.includes('qarton-isolated-home-runtime'));
assert.ok(prep.includes('window.__qartonSetAppState(f==="game"?"GAME":f==="intro"?"INTRO"'));
assert.ok(!premium.includes('findMenu')&&!premium.includes('.game-timer')&&!premium.includes('home-actions'));
assert.ok(premium.includes('window.__QARTON_APP_STATE__!=="GAME"'));
assert.ok(legacy.includes('index-legacy.html'));
console.log('PASS: QARTON HOME is independent from legacy menu DOM and uses explicit action APIs.');
